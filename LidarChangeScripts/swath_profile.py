"""Swath profiles: the BEFORE and AFTER ground points along a line picked on
the change map, drawn as a cross-section.

A swath is a strip SWATH_WIDTH wide centered on the profile line A -> A'.
Every point in it gets two coordinates:

    along  -- distance from A, measured along the line (the section's x axis)
    across -- signed distance from the centerline (+ = left of A -> A')

Plotting elevation against "along" squashes the swath's width onto the
centerline. On ground that also slopes across the swath, that smears each
epoch into a band tan(cross-slope) x SWATH_WIDTH thick -- 0.6 m for a 1 m
swath on a 30 degree slope. There are two options to correct this:

    tilt_swath_view    -- rotate the whole cloud by one angle about the
                          profile line and project it (rigid transformation).
    remove_cross_slope -- de-tilt every station by its own cross-slope, read
                          from the DEM. The swath collapses the whole way
                          along, but the shear coefficient changes with
                          station.

Either way both epochs get the same correction, so every vertical separation
between them at the same (along, across) survives untouched -- neither mode
can invent or hide change.

The AFTER tiles saved in the outputs are from before ICP alignment, so the
ICP transform generated by process_tile_pairs (icp_transforms.json) is
applied to them here -- the two epochs align as they were calculated by M3C2.
"""
